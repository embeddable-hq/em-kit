#!/usr/bin/env node
// Writes, from scripts/components.manifest.mjs and the synced tree:
//
//   src/componentDefaults.generated.ts  each published component's Embeddable
//     builder defaults (src/builderDefaults.generated.json, written by the
//     sync), kept only where the key is one of the component's props, and
//     type-checked against them with `satisfies`
//   src/components.generated.ts  one export per 'exported' component under its
//     standalone name, with those defaults applied (src/withDefaults.tsx)
//
// Deterministic, and needs no upstream checkout.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { components } from './components.manifest.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/components.generated.ts');
const DEFAULTS_IN = path.join(ROOT, 'src/builderDefaults.generated.json');
const DEFAULTS_OUT = path.join(ROOT, 'src/componentDefaults.generated.ts');
const HEADER = '// Generated by scripts/exports.mjs from scripts/components.manifest.mjs. Do not edit.\n';

const builderDefaults = JSON.parse(fs.readFileSync(DEFAULTS_IN, 'utf8'));
const published = components.filter((c) => c.status !== 'skipped');
const errors = [];

const indexFile = (component) => path.join(ROOT, 'src/generated', component.path, 'index.tsx');

for (const component of published) {
  if (!fs.existsSync(indexFile(component))) errors.push(`${component.path}: not in src/generated (run npm run sync)`);
}
if (errors.length) fail();

const configFile = ts.readConfigFile(path.join(ROOT, 'tsconfig.json'), ts.sys.readFile);
const config = ts.parseJsonConfigFileContent(configFile.config, ts.sys, ROOT);
const program = ts.createProgram(published.map(indexFile), config.options);
const checker = program.getTypeChecker();

// The props type: the manifest's `props`, else the file's only exported
// `…Props`/`…Prop` type, else the one named after the directory.
const findPropsType = (component) => {
  const sourceFile = program.getSourceFile(indexFile(component));
  const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
  const exported = checker.getExportsOfModule(moduleSymbol);
  const names = exported.map((s) => s.name);
  if (!names.includes('default')) errors.push(`${component.path}/index.tsx: no default export`);
  const dir = component.path.split('/').pop();
  const candidates = names.filter((n) => /Props?$/.test(n));
  const name =
    component.props ??
    (candidates.length === 1 ? candidates[0] : candidates.find((n) => new RegExp(`^${dir}(Pro)?Props?$`).test(n)));
  const symbol = exported.find((s) => s.name === name);
  if (!symbol) {
    errors.push(`${component.path}/index.tsx: can't tell the props type (found ${candidates.join(', ') || 'none'}); set \`props\` in the manifest`);
    return undefined;
  }
  const resolved = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  const propNames = new Set(checker.getPropertiesOfType(checker.getDeclaredTypeOfSymbol(resolved)).map((p) => p.name));
  return { name, propNames };
};

const defaultsLines = [];
const typeImports = [];
const exportLines = [];
const dropped = [];

for (const component of published) {
  const propsType = findPropsType(component);
  if (!propsType) continue;
  const from = `./generated/${component.path}`;
  const typeAlias = `${component.name}BaseProps`;
  typeImports.push(`import type { ${propsType.name} as ${typeAlias} } from '${from}';`);

  // Builder inputs that aren't props (query settings such as maxResults) are
  // the data layer's business here.
  const entries = Object.entries(builderDefaults[component.path] ?? {}).filter(([key]) => {
    if (propsType.propNames.has(key)) return true;
    dropped.push(`${component.name}.${key}`);
    return false;
  });
  // A control's placeholder is the one default that is text a reader sees:
  // it becomes a "key|fallback" string, translated in src/i18n.
  const isControl = component.path.startsWith('components/editors/');
  const printed = (key, value) =>
    isControl && key === 'placeholder' && typeof value === 'string'
      ? `controls.placeholder.${component.name.charAt(0).toLowerCase()}${component.name.slice(1)}|${value}`
      : value;
  const body = entries.map(([key, value]) => `    ${key}: ${JSON.stringify(printed(key, value))},`).join('\n');
  defaultsLines.push(`  ${component.name}: {\n${body}\n  } satisfies Partial<${typeAlias}>,`);

  if (component.status === 'exported') {
    exportLines.push(
      `import ${component.name}Base from '${from}';`,
      `export type ${component.name}Props = ${typeAlias};`,
      `export const ${component.name} = withDefaults(${component.name}Base, componentDefaults.${component.name}, '${component.name}');`,
      '',
    );
  }
}

if (errors.length) fail();

fs.writeFileSync(
  DEFAULTS_OUT,
  `${HEADER}// Embeddable builder defaults per component; builder inputs that aren't props are left out:\n` +
    `// ${dropped.join(', ') || 'none'}.\n\n` +
    `${typeImports.join('\n')}\n\nexport const componentDefaults = {\n${defaultsLines.join('\n')}\n};\n`,
);

fs.writeFileSync(
  OUT,
  `${HEADER}// Upstream names drop their \`Pro\` suffix (BarChartDefaultPro → BarChart), and each\n` +
    `// component applies its Embeddable builder defaults (src/componentDefaults.generated.ts).\n\n` +
    `import { componentDefaults } from './componentDefaults.generated';\nimport { withDefaults } from './withDefaults';\n` +
    `${typeImports.filter((l) => exportLines.some((e) => e.includes(l.match(/as (\w+)/)[1]))).join('\n')}\n\n` +
    exportLines.join('\n'),
);

console.log(
  `Wrote ${exportLines.filter((l) => l.startsWith('export const')).length} component exports and defaults for ${published.length} components.`,
);

function fail() {
  console.error(`Exports failed:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

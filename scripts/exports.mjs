#!/usr/bin/env node
// Writes src/components.generated.ts from scripts/components.manifest.mjs:
// one default + props-type export per 'exported' component, under its
// standalone name. Runs after the sync; deterministic, needs no upstream.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { components } from './components.manifest.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/components.generated.ts');

const errors = [];
const lines = [];

for (const component of components.filter((c) => c.status === 'exported')) {
  const file = path.join(ROOT, 'src/generated', component.path, 'index.tsx');
  if (!fs.existsSync(file)) {
    errors.push(`${component.path}: not in src/generated (run npm run sync)`);
    continue;
  }
  const code = fs.readFileSync(file, 'utf8');
  if (!/^export default /m.test(code)) errors.push(`${component.path}/index.tsx: no default export`);

  // The props type: the manifest's `props`, else the file's only exported
  // `…Props`/`…Prop` type, else the one named after the directory.
  const dir = component.path.split('/').pop();
  const exportedTypes = [
    ...[...code.matchAll(/^export type (\w+)\s*=/gm)].map((m) => m[1]),
    ...[...code.matchAll(/^export type \{([^}]+)\}/gm)].flatMap((m) => m[1].split(',').map((n) => n.trim())),
  ];
  const candidates = exportedTypes.filter((n) => /Props?$/.test(n));
  const propsType =
    component.props ??
    (candidates.length === 1 ? candidates[0] : candidates.find((n) => new RegExp(`^${dir}(Pro)?Props?$`).test(n)));
  if (!propsType || !exportedTypes.includes(propsType)) {
    errors.push(
      `${component.path}/index.tsx: can't tell the props type (found ${candidates.join(', ') || 'none'}); set \`props\` in the manifest`,
    );
    continue;
  }

  const from = `./generated/${component.path}`;
  lines.push(`export { default as ${component.name}, type ${propsType} as ${component.name}Props } from '${from}';`);
}

if (errors.length) {
  console.error(`Exports failed:\n  ${errors.join('\n  ')}`);
  process.exit(1);
}

const header = `// Generated by scripts/exports.mjs from scripts/components.manifest.mjs. Do not edit.\n// Upstream names drop their \`Pro\` suffix: BarChartDefaultPro → BarChart.\n\n`;
fs.writeFileSync(OUT, `${header}${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length} component exports to src/components.generated.ts.`);
